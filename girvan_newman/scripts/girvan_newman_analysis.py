#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
girvan_newman_analysis.py

Purpose:
    Implement Girvan-Newman community detection on the cosine similarity graph
    generated by the Steam dataset graph pipeline.

    The Girvan-Newman algorithm iteratively removes edges with highest betweenness
    centrality to identify communities in the network.

Input:
    --edges           CSV with columns: src_appid,dst_appid,cosine (supports .gz files)
    --out-dir         Output directory for analysis results
    --max-communities Number of communities to detect (default: 10)
    --min-community-size  Minimum size of communities to keep (default: 5)

Optional filters:
    --min-weight      Keep edges with cosine >= X (default: 0.7)
    --giant-only      Only analyze the largest connected component
    --kcore K         Reduce graph to K-core before analysis
    --max-nodes N     If graph exceeds N nodes, sample down (degree-based)

Output:
    - community_assignments.csv: Node-to-community mapping
    - community_stats.json: Statistics about detected communities
    - community_dendogram.png: Hierarchical view of community splits
    - modularity_scores.csv: Modularity at each split level

Usage:
    python girvan_newman_analysis.py --edges ./out/graph_runs/.../edges_top100.csv.gz --out-dir ./out/girvan_newman/
"""

import argparse
import csv
import json
import sys
import gzip
from pathlib import Path
from collections import defaultdict
from typing import Dict, List, Optional, Tuple, Set

import pandas as pd
import numpy as np
import networkx as nx
import matplotlib.pyplot as plt
import matplotlib
matplotlib.use('Agg')  # headless mode


def load_edges_from_csv(edges_path: Path, min_weight: Optional[float] = None, max_edges: Optional[int] = None) -> List[Tuple[str, str, float]]:
    """Load edges from CSV file, supporting both regular and gzipped files."""
    edges = []
    
    def open_file(path):
        if path.suffix == '.gz':
            return gzip.open(path, 'rt')
        else:
            return open(path, 'r')
    
    print(f"[INFO] Loading edges from {edges_path}")
    
    with open_file(edges_path) as f:
        reader = csv.DictReader(f)
        for i, row in enumerate(reader):
            try:
                src = str(row['src_appid'])
                dst = str(row['dst_appid'])
                weight = float(row['cosine'])
                
                if min_weight is not None and weight < min_weight:
                    continue
                
                edges.append((src, dst, weight))
                
                if max_edges and len(edges) >= max_edges:
                    print(f"[INFO] Reached max_edges limit ({max_edges}), stopping")
                    break
                    
                if (i + 1) % 100000 == 0:
                    print(f"[INFO] Processed {i+1:,} rows, kept {len(edges):,} edges")
                    
            except (ValueError, KeyError) as e:
                print(f"[WARN] Skipping invalid row {i}: {e}")
                continue
    
    print(f"[INFO] Loaded {len(edges):,} edges")
    return edges


def create_graph_from_edges(edges: List[Tuple[str, str, float]], 
                           giant_only: bool = True, 
                           kcore: Optional[int] = None,
                           max_nodes: Optional[int] = None) -> nx.Graph:
    """Create NetworkX graph from edges with optional filters."""
    G = nx.Graph()
    
    print(f"[INFO] Building graph from {len(edges):,} edges")
    
    # Add edges to graph
    for src, dst, weight in edges:
        if src != dst:  # No self-loops
            # Keep the maximum weight if edge already exists
            if G.has_edge(src, dst):
                if weight > G[src][dst]['weight']:
                    G[src][dst]['weight'] = weight
            else:
                G.add_edge(src, dst, weight=weight)
    
    print(f"[INFO] Initial graph: {G.number_of_nodes():,} nodes, {G.number_of_edges():,} edges")
    
    # Apply k-core filter
    if kcore is not None and kcore > 0:
        G = nx.k_core(G, k=kcore)
        print(f"[INFO] After {kcore}-core filter: {G.number_of_nodes():,} nodes, {G.number_of_edges():,} edges")
    
    # Keep only giant component
    if giant_only and G.number_of_nodes() > 0:
        components = list(nx.connected_components(G))
        if components:
            largest_cc = max(components, key=len)
            G = G.subgraph(largest_cc).copy()
            print(f"[INFO] Giant component: {G.number_of_nodes():,} nodes, {G.number_of_edges():,} edges")
    
    # Sample nodes if too many
    if max_nodes is not None and G.number_of_nodes() > max_nodes:
        degrees = dict(G.degree())
        top_nodes = sorted(degrees.keys(), key=degrees.get, reverse=True)[:max_nodes]
        G = G.subgraph(top_nodes).copy()
        print(f"[INFO] After sampling top {max_nodes} nodes: {G.number_of_nodes():,} nodes, {G.number_of_edges():,} edges")
    
    return G


def girvan_newman_communities(G: nx.Graph, max_communities: int = 10) -> Tuple[List[Set[str]], List[float], List[int]]:
    """
    Apply Girvan-Newman algorithm to detect communities.
    
    Returns:
        - List of community sets at each level
        - Modularity scores at each level
        - Number of communities at each level
    """
    if G.number_of_nodes() == 0:
        return [], [], []
    
    print(f"[INFO] Running Girvan-Newman on graph with {G.number_of_nodes():,} nodes, {G.number_of_edges():,} edges")
    
    # Use NetworkX's implementation
    communities_generator = nx.algorithms.community.girvan_newman(G)
    
    all_communities = []
    modularities = []
    num_communities = []
    
    try:
        for i in range(max_communities):
            communities = next(communities_generator)
            community_list = [set(c) for c in communities]
            
            # Calculate modularity
            modularity = nx.algorithms.community.modularity(G, communities)
            
            all_communities.append(community_list)
            modularities.append(modularity)
            num_communities.append(len(community_list))
            
            print(f"[INFO] Level {i+1}: {len(community_list)} communities, modularity = {modularity:.4f}")
            
            # Print community sizes
            sizes = sorted([len(c) for c in community_list], reverse=True)
            print(f"[INFO] Community sizes: {sizes[:10]}{'...' if len(sizes) > 10 else ''}")
            
    except StopIteration:
        print(f"[INFO] Algorithm converged after {len(all_communities)} levels")
    
    return all_communities, modularities, num_communities


def filter_communities_by_size(communities: List[Set[str]], min_size: int) -> List[Set[str]]:
    """Filter out communities smaller than min_size."""
    filtered = [c for c in communities if len(c) >= min_size]
    removed_count = len(communities) - len(filtered)
    if removed_count > 0:
        print(f"[INFO] Filtered out {removed_count} communities smaller than {min_size} nodes")
    return filtered


def save_community_assignments(communities: List[Set[str]], output_path: Path, level: int):
    """Save community assignments to CSV."""
    assignments = []
    for community_id, community in enumerate(communities):
        for node in community:
            assignments.append({
                'node_id': node,
                'community_id': community_id,
                'level': level,
                'community_size': len(community)
            })
    
    df = pd.DataFrame(assignments)
    df.to_csv(output_path, index=False)
    print(f"[INFO] Saved community assignments to {output_path}")


def save_community_stats(all_communities: List[List[Set[str]]], 
                        modularities: List[float], 
                        num_communities: List[int], 
                        output_path: Path):
    """Save community detection statistics."""
    stats = {
        'levels': len(all_communities),
        'max_modularity': max(modularities) if modularities else 0,
        'max_modularity_level': modularities.index(max(modularities)) if modularities else 0,
        'modularity_scores': modularities,
        'num_communities_per_level': num_communities,
        'community_sizes_per_level': []
    }
    
    for communities in all_communities:
        sizes = [len(c) for c in communities]
        stats['community_sizes_per_level'].append({
            'sizes': sorted(sizes, reverse=True),
            'mean_size': np.mean(sizes),
            'std_size': np.std(sizes),
            'min_size': min(sizes),
            'max_size': max(sizes)
        })
    
    with open(output_path, 'w') as f:
        json.dump(stats, f, indent=2)
    print(f"[INFO] Saved community stats to {output_path}")


def plot_modularity_scores(modularities: List[float], output_path: Path):
    """Plot modularity scores vs number of communities."""
    if not modularities:
        return
        
    plt.figure(figsize=(10, 6))
    levels = list(range(1, len(modularities) + 1))
    plt.plot(levels, modularities, 'o-', linewidth=2, markersize=8)
    plt.xlabel('Number of Communities')
    plt.ylabel('Modularity Score')
    plt.title('Modularity vs Number of Communities (Girvan-Newman)')
    plt.grid(True, alpha=0.3)
    
    # Mark the maximum
    max_idx = modularities.index(max(modularities))
    plt.axvline(x=max_idx+1, color='red', linestyle='--', alpha=0.7)
    plt.text(max_idx+1, max(modularities), f'  Max: {max(modularities):.4f}', 
             verticalalignment='bottom')
    
    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close()
    print(f"[INFO] Saved modularity plot to {output_path}")


def plot_community_size_distribution(communities: List[Set[str]], output_path: Path, level: int):
    """Plot distribution of community sizes."""
    sizes = [len(c) for c in communities]
    
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(15, 6))
    
    # Histogram
    ax1.hist(sizes, bins=min(20, len(set(sizes))), alpha=0.7, edgecolor='black')
    ax1.set_xlabel('Community Size')
    ax1.set_ylabel('Frequency')
    ax1.set_title(f'Community Size Distribution (Level {level})')
    ax1.grid(True, alpha=0.3)
    
    # Box plot
    ax2.boxplot(sizes, vert=False)
    ax2.set_xlabel('Community Size')
    ax2.set_title(f'Community Size Box Plot (Level {level})')
    ax2.grid(True, alpha=0.3)
    
    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close()
    print(f"[INFO] Saved community size distribution to {output_path}")


def main():
    parser = argparse.ArgumentParser(description='Girvan-Newman community detection on Steam game similarity graph')
    parser.add_argument('--edges', required=True, help='Path to edges CSV file (supports .gz)')
    parser.add_argument('--out-dir', required=True, help='Output directory for results')
    parser.add_argument('--max-communities', type=int, default=10, help='Maximum number of community levels to detect')
    parser.add_argument('--min-community-size', type=int, default=5, help='Minimum community size to keep')
    
    # Graph filters
    parser.add_argument('--min-weight', type=float, default=0.7, help='Minimum edge weight (cosine similarity)')
    parser.add_argument('--giant-only', action='store_true', help='Only analyze largest connected component')
    parser.add_argument('--kcore', type=int, default=None, help='Apply k-core filter')
    parser.add_argument('--max-nodes', type=int, default=None, help='Maximum nodes to analyze (degree-based sampling)')
    parser.add_argument('--max-edges', type=int, default=None, help='Maximum edges to load (for testing)')
    
    args = parser.parse_args()
    
    # Create output directory
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    
    # Load edges
    edges = load_edges_from_csv(Path(args.edges), args.min_weight, args.max_edges)
    
    if not edges:
        print("[ERROR] No edges loaded, exiting")
        sys.exit(1)
    
    # Create graph
    G = create_graph_from_edges(edges, args.giant_only, args.kcore, args.max_nodes)
    
    if G.number_of_nodes() == 0:
        print("[ERROR] Empty graph after filtering, exiting")
        sys.exit(1)
    
    # Run Girvan-Newman
    all_communities, modularities, num_communities = girvan_newman_communities(G, args.max_communities)
    
    if not all_communities:
        print("[ERROR] No communities detected, exiting")
        sys.exit(1)
    
    # Save results for each level
    for level, communities in enumerate(all_communities):
        filtered_communities = filter_communities_by_size(communities, args.min_community_size)
        
        if filtered_communities:
            # Save assignments
            assignments_path = out_dir / f'community_assignments_level_{level+1}.csv'
            save_community_assignments(filtered_communities, assignments_path, level+1)
            
            # Plot community size distribution
            dist_path = out_dir / f'community_sizes_level_{level+1}.png'
            plot_community_size_distribution(filtered_communities, dist_path, level+1)
    
    # Find best level (highest modularity)
    best_level = modularities.index(max(modularities))
    best_communities = filter_communities_by_size(all_communities[best_level], args.min_community_size)
    
    # Save best level assignments
    best_path = out_dir / 'community_assignments_best.csv'
    save_community_assignments(best_communities, best_path, best_level+1)
    
    # Save statistics
    stats_path = out_dir / 'community_stats.json'
    save_community_stats(all_communities, modularities, num_communities, stats_path)
    
    # Save modularity scores
    mod_df = pd.DataFrame({
        'level': range(1, len(modularities) + 1),
        'num_communities': num_communities,
        'modularity': modularities
    })
    mod_path = out_dir / 'modularity_scores.csv'
    mod_df.to_csv(mod_path, index=False)
    
    # Plot modularity
    mod_plot_path = out_dir / 'modularity_plot.png'
    plot_modularity_scores(modularities, mod_plot_path)
    
    print(f"\n[SUCCESS] Girvan-Newman analysis completed!")
    print(f"Output directory: {out_dir}")
    print(f"Best modularity: {max(modularities):.4f} at level {best_level+1}")
    print(f"Best level has {len(best_communities)} communities (min size {args.min_community_size})")


if __name__ == '__main__':
    main()