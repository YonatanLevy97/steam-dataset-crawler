#!/usr/bin/env python3
"""
Generate Complete Steam Communities Visualization Suite

This runs ALL 6 analysis categories with full visualization generation:
1. Community Overview
2. Genre & Category Analysis  
3. Publisher & Developer Analysis
4. Temporal & Rating Analysis
5. Technical Features Analysis
6. Similarity Analysis

Generates 50+ visualizations across all categories.
"""

import sys
import os
from pathlib import Path
import matplotlib.pyplot as plt
import time

# Set matplotlib backend to non-interactive
plt.switch_backend('Agg')

# Add the communities_visualizations directory to Python path
viz_dir = Path(__file__).parent / "communities_visualizations"
sys.path.insert(0, str(viz_dir))

def main():
    print("🎨 Steam Communities Complete Visualization Suite")
    print("=" * 60)
    print("🎯 Running ALL 6 analysis categories")
    print("📊 Will generate 50+ comprehensive visualizations")
    print("⏱️ Estimated time: 5-10 minutes")
    print("=" * 60)
    
    try:
        from generate_all_plots import VisualizationOrchestrator
        
        # Create orchestrator for full generation
        print("🏗️ Initializing complete visualization orchestrator...")
        orchestrator = VisualizationOrchestrator(
            data_dir=None,  # Use default paths
            output_dir="communities_visualizations/outputs/complete_suite",
            verbose=True
        )
        
        # Generate ALL categories
        print("\n🎯 Starting COMPLETE visualization generation...")
        print("📝 This will generate all 6 analysis categories:")
        print("   1️⃣ Community Overview - sizes, composition, pricing")
        print("   2️⃣ Genre Analysis - distributions, diversity, clustering")  
        print("   3️⃣ Publisher Analysis - concentration, networks, market dynamics")
        print("   4️⃣ Temporal Analysis - release timelines, quality evolution")
        print("   5️⃣ Technical Features - language support, platform compatibility")
        print("   6️⃣ Similarity Analysis - distance matrices, clustering validation")
        
        input("\n👆 Press Enter to start complete generation (or Ctrl+C to cancel)...")
        
        # Run ALL categories (this is the full suite)
        all_categories = ['overview', 'genres', 'publishers', 'temporal', 'technical', 'similarity']
        
        results = orchestrator.generate_all_visualizations(categories=all_categories)
        
        if results['success']:
            report = results['report']
            print(f"\n🎉 COMPLETE SUCCESS!")
            print(f"📊 Generated {report['generation_summary']['total_plots_generated']} total visualizations")
            print(f"⏱️ Completed in {report['generation_summary']['duration_formatted']}")
            print(f"📁 Output directory: {report['generation_summary']['output_directory']}")
            
            # Show detailed breakdown
            print(f"\n📋 Generated by Category:")
            for category in all_categories:
                if category in results['results'] and results['results'][category]:
                    plot_count = len(results['results'][category])
                    print(f"   ✅ {category.title()}: {plot_count} visualizations")
                else:
                    print(f"   ⚠️ {category.title()}: Failed to generate")
            
            print(f"\n📄 Detailed reports:")
            print(f"   📋 JSON Report: {results['output_directory']}/generation_report.json")
            print(f"   📝 Markdown Report: {results['output_directory']}/generation_report.md")
            
            # Show file counts
            output_path = Path(results['output_directory'])
            png_files = list(output_path.rglob('*.png'))
            html_files = list(output_path.rglob('*.html'))
            pdf_files = list(output_path.rglob('*.pdf'))
            csv_files = list(output_path.rglob('*.csv'))
            
            print(f"\n📈 Generated Files Summary:")
            print(f"   🖼️ Static Images (PNG): {len(png_files)}")
            print(f"   📄 PDFs: {len(pdf_files)}")
            print(f"   🌐 Interactive (HTML): {len(html_files)}")
            print(f"   📊 Data Exports (CSV): {len(csv_files)}")
            print(f"   📋 Total Files: {len(png_files) + len(html_files) + len(pdf_files) + len(csv_files)}")
            
            print(f"\n🎯 WHAT'S BEEN CREATED:")
            print(f"   📁 Complete visualization suite in: {results['output_directory']}")
            print(f"   📊 Publication-ready static charts (PNG/PDF)")
            print(f"   🌐 Interactive web visualizations (HTML)")
            print(f"   📈 Processed datasets for further analysis (CSV)")
            print(f"   📋 Comprehensive generation reports (JSON/MD)")
            
            print(f"\n✨ Ready for:")
            print(f"   📝 Academic/business presentations")
            print(f"   🌐 Web dashboard deployment") 
            print(f"   📊 Further data analysis")
            print(f"   📋 Report generation")
            
            return 0
        else:
            print(f"❌ Generation failed: {results.get('error', 'Unknown error')}")
            return 1
            
    except KeyboardInterrupt:
        print("\n👋 Generation interrupted by user")
        return 130
    except Exception as e:
        print(f"❌ Unexpected error: {e}")
        import traceback
        traceback.print_exc()
        return 1

if __name__ == "__main__":
    exit(main())