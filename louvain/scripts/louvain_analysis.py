#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
louvain_analysis.py

Purpose:
    Implement Louvain community detection on the cosine similarity graph
    generated by the Steam dataset graph pipeline.

    The Louvain algorithm optimizes modularity by iteratively moving nodes
    between communities to maximize the modularity score.

Input:
    --edges           CSV with columns: src_appid,dst_appid,cosine (supports .gz files)
    --out-dir         Output directory for analysis results
    --min-community-size  Minimum size of communities to keep (default: 5)

Louvain-specific parameters:
    --resolution      Resolution parameter controlling community size (default: 1.0)
    --random-seed     Random seed for reproducibility (default: 42)

Optional filters:
    --min-weight      Keep edges with cosine >= X (default: 0.7)
    --giant-only      Only analyze the largest connected component
    --kcore K         Reduce graph to K-core before analysis
    --max-nodes N     If graph exceeds N nodes, sample down (degree-based)
    --max-edges N     Maximum edges to load (useful for testing)

Output:
    - community_assignments.csv: Node-to-community mapping
    - community_stats.json: Statistics about detected communities
    - community_sizes.png: Community size distribution
    - modularity_info.json: Modularity score and parameters

Usage:
    python louvain_analysis.py --edges ./out/graph_runs/.../edges_top100.csv.gz --out-dir ./out/louvain/
"""

import argparse
import csv
import json
import sys
import gzip
from pathlib import Path
from collections import defaultdict, Counter
from typing import Dict, List, Optional, Tuple, Set

import pandas as pd
import numpy as np
import networkx as nx
import matplotlib.pyplot as plt
import matplotlib
matplotlib.use('Agg')  # headless mode


def load_edges_from_csv(edges_path: Path, min_weight: Optional[float] = None, max_edges: Optional[int] = None) -> List[Tuple[str, str, float]]:
    """Load edges from CSV file, supporting both regular and gzipped files."""
    edges = []
    
    def open_file(path):
        if path.suffix == '.gz':
            return gzip.open(path, 'rt')
        else:
            return open(path, 'r')
    
    print(f"[INFO] Loading edges from {edges_path}")
    
    with open_file(edges_path) as f:
        reader = csv.DictReader(f)
        for i, row in enumerate(reader):
            try:
                src = str(row['src_appid'])
                dst = str(row['dst_appid'])
                weight = float(row['cosine'])
                
                if min_weight is not None and weight < min_weight:
                    continue
                
                edges.append((src, dst, weight))
                
                if max_edges and len(edges) >= max_edges:
                    print(f"[INFO] Reached max_edges limit ({max_edges}), stopping")
                    break
                    
                if (i + 1) % 100000 == 0:
                    print(f"[INFO] Processed {i+1:,} rows, kept {len(edges):,} edges")
                    
            except (ValueError, KeyError) as e:
                print(f"[WARN] Skipping invalid row {i}: {e}")
                continue
    
    print(f"[INFO] Loaded {len(edges):,} edges")
    return edges


def create_graph_from_edges(edges: List[Tuple[str, str, float]], 
                           giant_only: bool = True, 
                           kcore: Optional[int] = None,
                           max_nodes: Optional[int] = None) -> nx.Graph:
    """Create NetworkX graph from edges with optional filters."""
    G = nx.Graph()
    
    print(f"[INFO] Building graph from {len(edges):,} edges")
    
    # Add edges with weights
    for src, dst, weight in edges:
        G.add_edge(src, dst, weight=weight)
    
    print(f"[INFO] Initial graph: {G.number_of_nodes():,} nodes, {G.number_of_edges():,} edges")
    
    # Apply giant component filter
    if giant_only and not nx.is_connected(G):
        print("[INFO] Extracting largest connected component...")
        giant = max(nx.connected_components(G), key=len)
        G = G.subgraph(giant).copy()
        print(f"[INFO] Giant component: {G.number_of_nodes():,} nodes, {G.number_of_edges():,} edges")
    
    # Apply k-core filter
    if kcore is not None:
        print(f"[INFO] Applying {kcore}-core filter...")
        G = nx.k_core(G, k=kcore)
        print(f"[INFO] After {kcore}-core: {G.number_of_nodes():,} nodes, {G.number_of_edges():,} edges")
    
    # Apply node limit by sampling high-degree nodes
    if max_nodes is not None and G.number_of_nodes() > max_nodes:
        print(f"[INFO] Sampling down to {max_nodes:,} nodes...")
        degrees = dict(G.degree())
        top_nodes = sorted(degrees.keys(), key=lambda x: degrees[x], reverse=True)[:max_nodes]
        G = G.subgraph(top_nodes).copy()
        print(f"[INFO] After sampling: {G.number_of_nodes():,} nodes, {G.number_of_edges():,} edges")
    
    return G


def louvain_communities(G: nx.Graph, resolution: float = 1.0, random_seed: int = 42) -> Tuple[List[Set[str]], float]:
    """
    Apply Louvain algorithm to detect communities.
    Returns: (community_list, modularity_score)
    """
    print(f"[INFO] Running Louvain algorithm with resolution={resolution}, seed={random_seed}")
    
    try:
        # NetworkX >= 2.8 has community.louvain_communities
        from networkx.algorithms import community as nx_community
        communities = nx_community.louvain_communities(G, resolution=resolution, seed=random_seed)
    except (ImportError, AttributeError):
        try:
            # Fallback to python-louvain if available
            import community as community_louvain
            print("[INFO] Using python-louvain fallback")
            partition = community_louvain.best_partition(G, resolution=resolution, random_state=random_seed)
            # Convert partition dict to list of sets
            community_dict = defaultdict(set)
            for node, comm_id in partition.items():
                community_dict[comm_id].add(node)
            communities = list(community_dict.values())
        except ImportError:
            print("[ERROR] Neither NetworkX >= 2.8 nor python-louvain is available")
            print("[ERROR] Please install python-louvain: pip install python-louvain")
            sys.exit(1)
    
    # Convert to list of sets if needed
    communities = [set(c) for c in communities]
    
    # Calculate modularity
    modularity = nx.community.modularity(G, communities)
    
    print(f"[INFO] Detected {len(communities)} communities with modularity {modularity:.4f}")
    
    return communities, modularity


def save_community_assignments(communities: List[Set[str]], output_path: Path, min_size: int = 5) -> None:
    """Save community assignments to CSV file."""
    print(f"[INFO] Saving community assignments to {output_path}")
    
    # Filter communities by minimum size
    filtered_communities = [c for c in communities if len(c) >= min_size]
    
    if len(filtered_communities) < len(communities):
        print(f"[INFO] Filtered {len(communities) - len(filtered_communities)} communities smaller than {min_size} nodes")
    
    assignments = []
    for comm_id, community in enumerate(filtered_communities):
        for node in community:
            assignments.append({
                'node_id': node,
                'community_id': comm_id,
                'community_size': len(community)
            })
    
    # Sort by community_id, then by node_id
    assignments.sort(key=lambda x: (x['community_id'], x['node_id']))
    
    with open(output_path, 'w', newline='') as f:
        fieldnames = ['node_id', 'community_id', 'community_size']
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(assignments)
    
    print(f"[INFO] Saved {len(assignments)} community assignments")


def save_community_stats(communities: List[Set[str]], modularity: float, output_path: Path, 
                        resolution: float, random_seed: int, min_size: int) -> None:
    """Save community statistics to JSON file."""
    print(f"[INFO] Saving community stats to {output_path}")
    
    # Filter communities by minimum size
    filtered_communities = [c for c in communities if len(c) >= min_size]
    community_sizes = [len(c) for c in filtered_communities]
    
    stats = {
        'algorithm': 'louvain',
        'total_communities': len(filtered_communities),
        'total_nodes': sum(community_sizes),
        'modularity': round(modularity, 6),
        'resolution_used': resolution,
        'random_seed': random_seed,
        'min_community_size': min_size,
        'community_sizes': sorted(community_sizes, reverse=True),
        'size_statistics': {
            'mean': round(np.mean(community_sizes), 2) if community_sizes else 0,
            'median': round(np.median(community_sizes), 2) if community_sizes else 0,
            'std': round(np.std(community_sizes), 2) if community_sizes else 0,
            'min': min(community_sizes) if community_sizes else 0,
            'max': max(community_sizes) if community_sizes else 0
        }
    }
    
    with open(output_path, 'w') as f:
        json.dump(stats, f, indent=2)
    
    print(f"[INFO] Community stats: {len(filtered_communities)} communities, modularity {modularity:.4f}")


def plot_community_size_distribution(communities: List[Set[str]], output_path: Path, min_size: int = 5) -> None:
    """Plot community size distribution."""
    print(f"[INFO] Plotting community size distribution to {output_path}")
    
    # Filter communities by minimum size
    filtered_communities = [c for c in communities if len(c) >= min_size]
    community_sizes = [len(c) for c in filtered_communities]
    
    if not community_sizes:
        print("[WARN] No communities to plot")
        return
    
    plt.figure(figsize=(12, 6))
    
    # Histogram
    plt.subplot(1, 2, 1)
    plt.hist(community_sizes, bins=min(20, len(set(community_sizes))), edgecolor='black', alpha=0.7)
    plt.xlabel('Community Size')
    plt.ylabel('Frequency')
    plt.title(f'Community Size Distribution\n({len(community_sizes)} communities)')
    plt.grid(True, alpha=0.3)
    
    # Box plot
    plt.subplot(1, 2, 2)
    plt.boxplot(community_sizes, vert=True)
    plt.ylabel('Community Size')
    plt.title('Community Size Statistics')
    plt.grid(True, alpha=0.3)
    
    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close()


def save_modularity_info(modularity: float, output_path: Path, resolution: float, random_seed: int) -> None:
    """Save modularity information to JSON file."""
    modularity_info = {
        'modularity': round(modularity, 6),
        'algorithm': 'louvain',
        'parameters': {
            'resolution': resolution,
            'random_seed': random_seed
        }
    }
    
    with open(output_path, 'w') as f:
        json.dump(modularity_info, f, indent=2)


def main():
    parser = argparse.ArgumentParser(
        description="Apply Louvain community detection to Steam game similarity graph",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Basic community detection
  python louvain_analysis.py --edges ./out/graph_runs/.../edges_top100.csv.gz --out-dir ./out/louvain/

  # With custom resolution for smaller communities
  python louvain_analysis.py --edges ./out/graph_runs/.../edges_top100.csv.gz \\
                              --out-dir ./out/louvain/ --resolution 1.5

  # Focused analysis on giant component with k-core filter
  python louvain_analysis.py --edges ./out/graph_runs/.../edges_top100.csv.gz \\
                              --giant-only --kcore 3 --resolution 0.8
        """
    )
    
    # Required arguments
    parser.add_argument('--edges', required=True, type=Path,
                       help='Path to edges CSV file (supports .gz)')
    parser.add_argument('--out-dir', required=True, type=Path,
                       help='Output directory for results')
    
    # Community detection parameters
    parser.add_argument('--min-community-size', type=int, default=5,
                       help='Minimum community size to keep (default: 5)')
    
    # Louvain-specific parameters
    parser.add_argument('--resolution', type=float, default=1.0,
                       help='Resolution parameter - higher values = smaller communities (default: 1.0)')
    parser.add_argument('--random-seed', type=int, default=42,
                       help='Random seed for reproducibility (default: 42)')
    
    # Graph filtering options
    parser.add_argument('--min-weight', type=float, default=0.7,
                       help='Minimum edge weight (cosine similarity) (default: 0.7)')
    parser.add_argument('--giant-only', action='store_true',
                       help='Only analyze largest connected component')
    parser.add_argument('--kcore', type=int, default=None,
                       help='Apply k-core filter before analysis')
    parser.add_argument('--max-nodes', type=int, default=None,
                       help='Maximum nodes to analyze (degree-based sampling)')
    parser.add_argument('--max-edges', type=int, default=None,
                       help='Maximum edges to load (useful for testing)')
    
    args = parser.parse_args()
    
    # Create output directory
    args.out_dir.mkdir(parents=True, exist_ok=True)
    print(f"[INFO] Output directory: {args.out_dir}")
    
    # Load edges
    edges = load_edges_from_csv(args.edges, min_weight=args.min_weight, max_edges=args.max_edges)
    
    if not edges:
        print("[ERROR] No edges loaded. Check file format and filters.")
        sys.exit(1)
    
    # Create graph
    G = create_graph_from_edges(edges, 
                               giant_only=args.giant_only,
                               kcore=args.kcore,
                               max_nodes=args.max_nodes)
    
    if G.number_of_nodes() == 0:
        print("[ERROR] Empty graph after filtering. Relaxing constraints or check input.")
        sys.exit(1)
    
    print(f"[INFO] Final graph for analysis: {G.number_of_nodes():,} nodes, {G.number_of_edges():,} edges")
    
    # Run Louvain community detection
    communities, modularity = louvain_communities(G, resolution=args.resolution, random_seed=args.random_seed)
    
    # Save results
    community_assignments_path = args.out_dir / "community_assignments.csv"
    save_community_assignments(communities, community_assignments_path, args.min_community_size)
    
    community_stats_path = args.out_dir / "community_stats.json"
    save_community_stats(communities, modularity, community_stats_path, 
                        args.resolution, args.random_seed, args.min_community_size)
    
    community_sizes_plot_path = args.out_dir / "community_sizes.png"
    plot_community_size_distribution(communities, community_sizes_plot_path, args.min_community_size)
    
    modularity_info_path = args.out_dir / "modularity_info.json"
    save_modularity_info(modularity, modularity_info_path, args.resolution, args.random_seed)
    
    print("\n" + "="*60)
    print("LOUVAIN COMMUNITY DETECTION COMPLETED")
    print("="*60)
    print(f"Communities detected: {len([c for c in communities if len(c) >= args.min_community_size])}")
    print(f"Modularity: {modularity:.4f}")
    print(f"Resolution used: {args.resolution}")
    print(f"Output directory: {args.out_dir}")
    print("\nGenerated files:")
    print(f"  - {community_assignments_path.name}")
    print(f"  - {community_stats_path.name}")
    print(f"  - {community_sizes_plot_path.name}")
    print(f"  - {modularity_info_path.name}")
    print("="*60)


if __name__ == "__main__":
    main()